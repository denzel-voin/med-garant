import { overlaps } from "@/lib/slots";

function d(minutes: number): Date {
    const base = new Date("2026-01-15T00:00:00.000Z");
    return new Date(base.getTime() + minutes * 60 * 1000);
}

describe("overlaps — алгоритм проверки пересечения интервалов", () => {
    // ── Непересекающиеся интервалы ─────────────────────────────────────────

    test("01. a целиком до b с зазором — нет пересечения", () => {
        expect(overlaps(d(0), d(10), d(20), d(30))).toBe(false);
    });

    test("02. b целиком до a с зазором — нет пересечения", () => {
        expect(overlaps(d(20), d(30), d(0), d(10))).toBe(false);
    });

    test("03. a.end === b.start — смежные интервалы не пересекаются", () => {
        // overlaps: s1 < e2 && e1 > s2 → e1 > s2 → d(10) > d(10) → false
        expect(overlaps(d(0), d(10), d(10), d(20))).toBe(false);
    });

    test("04. b.end === a.start — смежные интервалы не пересекаются", () => {
        // s1 < e2 → d(10) < d(10) → false
        expect(overlaps(d(10), d(20), d(0), d(10))).toBe(false);
    });

    // ── Частичное пересечение ──────────────────────────────────────────────

    test("05. частичное пересечение: a начинается раньше", () => {
        expect(overlaps(d(0), d(15), d(10), d(25))).toBe(true);
    });

    test("06. частичное пересечение: b начинается раньше", () => {
        expect(overlaps(d(10), d(25), d(0), d(15))).toBe(true);
    });

    // ── Полное вхождение ───────────────────────────────────────────────────

    test("07. a полностью содержит b", () => {
        expect(overlaps(d(0), d(30), d(10), d(20))).toBe(true);
    });

    test("08. b полностью содержит a", () => {
        expect(overlaps(d(10), d(20), d(0), d(30))).toBe(true);
    });

    // ── Граничные случаи ───────────────────────────────────────────────────

    test("09. одинаковые интервалы пересекаются", () => {
        expect(overlaps(d(10), d(20), d(10), d(20))).toBe(true);
    });

    test("10. однoминутное перекрытие в конце a", () => {
        // a: [0,11], b: [10,20] → пересечение [10,11]
        expect(overlaps(d(0), d(11), d(10), d(20))).toBe(true);
    });

    test("11. однoминутное перекрытие: b заканчивается сразу после начала a", () => {
        // a: [10,20], b: [9,11] → пересечение [10,11]
        expect(overlaps(d(10), d(20), d(9), d(11))).toBe(true);
    });

    test("12. нулевой интервал (точка) внутри другого — пересечение есть", () => {
        // a: [15,15], b: [10,20]
        // s1 < e2 → 15 < 20 ✓; e1 > s2 → 15 > 10 ✓
        expect(overlaps(d(15), d(15), d(10), d(20))).toBe(true);
    });
});